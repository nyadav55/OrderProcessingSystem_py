# Phase 4 — Behavioral Design Patterns
# This phase contains three patterns for managing how objects communicate and perform actions in your e-commerce application.
# Step	Pattern	Real-world example
# 4.1	Strategy	Choose standard or express shipping
# 4.2	Observer	Notify customers when an order status changes
# 4.3	Command	Execute or cancel order operations

# ==== Remember:
#  - Class: blueprint. 
#  - Object: instance of a class.
#  - __init__: initializes an object.
#  - self: refers to the current instance.